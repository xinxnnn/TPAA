"""Real 2048-bit synthetic registration -> audit -> memory experiment.

All identities are generated synthetic values. No authentication/TEE/real KYC.
"""
import argparse
from datetime import datetime, timezone
import json
from pathlib import Path
import secrets
from time import perf_counter

from crypto.primitives.paillier import Paillier
from crypto.memauth import chameleon as ch, executable_profile as p, issuance_experiment as issue, ps
from crypto.memauth.audit_events import APConstructPublic, TPFinalizePublic, observe, initial_memory
from crypto.memauth.memory import create, synchronization_witness
from crypto.memauth.synthetic_macro import append, construct
from crypto.memauth.srs import SRS
from crypto.memauth.continuity_primitives import prove, verify_equations
from crypto.memauth.topology_experiment import TopologyProof, verify as verify_topology
from crypto.memauth import accountability_experiment as accountability


def run(srs):
    start = perf_counter()
    paillier = Paillier(bits=2048)
    issuer = ps.SecretKey(secrets.randbelow(p.ORDER-1)+1, secrets.randbelow(p.ORDER-1)+1)
    pa = ch.keygen()  # PA role; never generated by TP/AP.
    ap_secret = secrets.randbelow(p.ORDER-1)+1
    af = secrets.token_bytes(32)
    identity_hash = p.h1('synthetic-person:' + secrets.token_hex(32))
    irf = issue.phc_init(paillier.n, identity_hash)
    rf = issue.pa_construct(paillier.n, irf, ap_secret, 'did:ap:synthetic', af)
    ap_time = datetime.now(timezone.utc).isoformat()
    ap_event = observe(ap_time, 'did:ap:synthetic', APConstructPublic(rf))
    finalized = issue.finalize(paillier.n, issuer, 'did:tp:synthetic', 'synthetic', pa.public,
                               ('module:chat:v1',), rf, af)
    tp_time = datetime.now(timezone.utc).isoformat()
    credential = finalized.credential
    tp_event = observe(tp_time, 'did:tp:synthetic', TPFinalizePublic(pa.public, credential.delta_tp))
    state, tp_macro, ap_macro = initial_memory(
        srs, credential.y0, credential.did_pa, pa.public, tp_event, ap_event,
        tp_rho=secrets.randbelow(p.ORDER), ap_rho=secrets.randbelow(p.ORDER))
    appended = append(ap_macro, [('synthetic-t3', 'use', 'synthetic-tool', 'synthetic-pa', 'local')], pa.secret)
    new_macro = construct('macro:new', 'synthetic-t4', credential.did_pa,
                          [('synthetic-t4', 'plan', 'synthetic-task', 'synthetic-pa', 'local')],
                          pa.public, randomness=secrets.randbelow(p.ORDER))
    s_user = secrets.token_bytes(32)
    theta = p.h1(s_user, p.scalar_bytes(pa.secret), p.scalar_bytes(credential.y0))
    updated = create(srs, state, (new_macro.point,), theta=theta)
    # KTP is in Zn; preserve that full value in the approved typed encoding.
    gamma = p.h1(credential.ktp, 'did:sa:synthetic')
    challenge = ap_macro.point.x
    algebra_proof = prove(srs, state, updated, challenge, gamma)
    cp_old = ch.backend.multiply(state.commitment, gamma, 1)
    k1 = ch.backend.multiply(ch.backend.generator(1), gamma, 1)
    old_witness = synchronization_witness(srs, state)
    topology = verify_topology(pa.public, challenge, ap_macro.ch_root, ap_macro.digests[0],
                               TopologyProof(appended.digests, appended.randomness))
    equation_checks = verify_equations(srs, cp_old, old_witness, k1, challenge,
                                       topology.y, algebra_proof)
    # Local synthetic role orchestration only; no approved tracing request is claimed.
    recovered = issue.recover_identity_hash(paillier.decrypt(rf), paillier.n, ap_secret,
                                            'did:ap:synthetic', af)
    blind_anchor = ch.backend.multiply(state.anchor, gamma, 1)
    opened_anchor = accountability.unblind(issuer, 'did:tp:synthetic', 'did:sa:synthetic',
                                           paillier.n, blind_anchor)
    located = accountability.locate(opened_anchor, (finalized.registration,))
    if located is None:
        raise ValueError('Phase 4 registration lookup failed')
    share = accountability.ap_share(ap_secret, 'did:ap:synthetic', located.af, paillier.n)
    link = accountability.finish(located, paillier.decrypt(located.rf), share,
                                  paillier.n, frozenset({identity_hash}))
    checks = {
        'IRF解密等式': paillier.decrypt(irf) == identity_hash,
        'PHC签名等式': ps.verify_phc_scalar(issuer.public_key(), credential.y0, credential.delta_tp),
        '联合解掩码等式': recovered == identity_hash,
        'Seq1来自TP事件': tp_macro.digests == (tp_event.event_digest,),
        'Seq2来自AP事件': ap_macro.digests == (ap_event.event_digest,),
        'APPEND保持CH': appended.ch_root == ap_macro.ch_root,
        'CREATE保留旧点': all(updated.polynomial(point.x) == point.y for point in state.points),
        'CREATE授权约束': updated.polynomial(theta) == state.initial_polynomial(theta),
        '身份锚保持': updated.anchor == state.anchor,
        '点打开配对等式': equation_checks['openingEquation'],
        '更新配对等式': equation_checks['updateEquation'],
        'topology重建与CH开口': topology.root == appended.root,
        '追责解盲与注册查找': opened_anchor == state.anchor and located.did_pa == credential.did_pa,
        '追责身份登记匹配': link is not None and link.identity_hash == identity_hash,
    }
    if not all(checks.values()):
        raise ValueError('Registration experiment invariant failed')
    return {
        'scope': '合成身份、本机角色仿真；真实密码运算；非完整认证或安全证明',
        'profile': p.manifest(), 'srsId': srs.identifier,
        'privacy': '注册阶段可关联工件；不属于匿名认证转录；无秘密值导出',
        'checks': checks,
        'steps': [
            {'operation': 'PHCInit / PAConstruct', 'source': 'PDF p6 Phase 0',
             'formula': 'IRF=Enc(H(ID)); RF=IRF*Enc(sAP) mod n²',
             'outputs': {'paillierModulusBits': paillier.n.bit_length()}, 'status': 'passed'},
            {'operation': 'PHCFinalize', 'source': 'PDF p6 Phase 0',
             'formula': 'δTP=g^(c1+c2*y0); KTP=PRF_c1(DIDTP || c2)',
             'outputs': {'PK_PA': pa.public.hex(), 'deltaTP': credential.delta_tp.hex()}, 'status': 'passed'},
            {'operation': '初始审计记忆', 'source': 'PDF p7 MemBuild + approved experiment audit',
             'formula': 'Seq1=H2(TP event); Seq2=H2(AP event); CP0=g^P0(alpha)',
             'outputs': {'TP': tp_event.public_trace(), 'AP': ap_event.public_trace(),
                         'commitment': state.commitment.hex(), 'degree': state.polynomial.degree}, 'status': 'passed'},
            {'operation': 'APPEND', 'source': 'PDF p7 MemUpdate',
             'formula': 'CH(Root;rho)=CH(Root_new;rho_new); P_new=P',
             'outputs': {'oldRoot': ap_macro.root.hex(), 'newRoot': appended.root.hex(),
                         'unchangedCH': ap_macro.ch_root.hex()}, 'status': 'passed'},
            {'operation': 'CREATE', 'source': 'PDF p7 MemUpdate',
             'formula': 'P_new=P+Q*Phi; P_new(theta)=P0(theta)',
             'outputs': {'commitment': updated.commitment.hex(), 'degree': updated.polynomial.degree}, 'status': 'passed'},
            {'operation': 'InitSync 见证计算', 'source': 'PDF p8 InitSync',
             'formula': 'W=h^phi(alpha)',
             'outputs': {'witnessG2': synchronization_witness(srs, updated).hex()}, 'status': 'passed'},
            {'operation': 'open / upd 原语验证', 'source': 'PDF p8 ContProve/ContVerify（仅两项等式）',
             'formula': 'e(CPnew/CPold,h)=e(pi_upd,Wold); e(CPnew/K1^y,h)=e(pi_open,h^(alpha-z))',
             'outputs': {'scope': 'y 来自独立 topology 校验；未执行 link/签名/身份验证，不是完整认证',
                         'acceptedCommitmentG1': cp_old.hex(), 'witnessOldG2': old_witness.hex(),
                         'K1': k1.hex(), 'currentCommitmentG1': algebra_proof.current_commitment.hex(),
                         'openingProofG1': algebra_proof.opening.hex(), 'updateProofG1': algebra_proof.update.hex(),
                         'equationResults': equation_checks}, 'status': 'passed'},
            {'operation': 'topology 实验校验', 'source': 'PDF p8 topo；显式实验注入 PKPA',
             'formula': 'Root=Merkle(Seq); Hkey∈Seq; CH_PKPA(Root,rho)=accepted_hRoot; y=H1(z||hRoot)',
             'outputs': {'scope': '全局 PA 公钥由本机编排器注入，可关联；不是匿名认证',
                         'root': topology.root.hex(), 'sequenceLength': topology.sequence_length,
                         'acceptedChRoot': ap_macro.ch_root.hex(),
                         'openingExport': 'rho 和完整开口不写入默认公开记录',
                         'ySource': '此校验得到的 y 直接用于 open 配对验证'}, 'status': 'passed'},
            {'operation': 'Bootstrap / 连续认证', 'source': 'PDF p7–8',
             'formula': '保留原文未定义符号及新旧承诺冲突',
             'outputs': {'reason': '用户要求仅诊断；未实现勘误，未执行认证'}, 'status': 'undefined'},
            {'operation': '联合追责等式实验', 'source': 'PDF p8 Phase 4',
             'formula': 'A=A_blind^(1/gamma); RegPA=lookup(A); H(ID)=(Dec(RF)-sAP) mod n',
             'outputs': {'scope': '仅本机合成角色等式实验；非已批准案件或真实身份披露',
                         'anchorLookupMatched': located.did_pa == credential.did_pa,
                         'identityLedgerMatched': link is not None,
                         'secretOutputs': '不导出 AP share、AF、身份哈希或身份明文'}, 'status': 'passed'},
        ],
        'elapsedMs': (perf_counter()-start)*1000,
    }


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--srs', type=Path, required=True)
    parser.add_argument('--output', type=Path, required=True)
    args = parser.parse_args()
    with args.srs.open(encoding='utf-8') as stream:
        srs = SRS.from_artifact(json.load(stream))
    trace = run(srs)
    with args.output.open('x', encoding='utf-8') as stream:
        json.dump(trace, stream, ensure_ascii=False, indent=2)
    print('Synthetic registration/memory trace written; all checks passed.')
