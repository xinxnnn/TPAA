P = int(_P_HEX, 16)
Q = (P - 1) // 2
G = 4
PARAMS_ID = "tpaa_v1/rfc3526-3072/g4"


def in_subgroup(x: int) -> bool:
    """x 是否属于 q 阶子群。外部传进来的群元素（AF、陷门公钥）一律先过这一关。"""
    return 1 < x < P and pow(x, Q, P) == 1


def rand_exp() -> int:
    """Z_q* 上的均匀随机指数（绑定随机数 r_bind 用它）。"""
    return randbelow(Q - 1) + 1


